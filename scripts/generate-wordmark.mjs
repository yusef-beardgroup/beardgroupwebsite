// Generates the Beard Group wordmark (src/components/Wordmark.astro) and the
// favicon (public/favicon.svg) as pure vector paths.
//
// "BEARD GROUP" is set in Tinos Bold and "LAW & BUSINESS PUBLISHERS" in Arimo:
// open-source (Apache 2.0) faces metrically compatible with the Times and Arial
// styles of the original logo. Both are converted to outlines, so the mark
// never depends on a web font loading. The divider ornament is traced from the
// existing logo artwork.
//
// Run with: npm run wordmark

import { readFileSync, writeFileSync } from 'node:fs';
import opentype from 'opentype.js';

const { Path, parse } = opentype;
const root = new URL('../', import.meta.url);

// All measurements are viewBox units with the title's cap height = 100,
// taken from the original logo.
const TITLE_CAP = 100;
const TITLE_WIDTH = 1018;
const RULE_TOP = 217;
const RULE_BOTTOM = 229;
const TAGLINE_TOP = 282;
const TAGLINE_CAP = 34;

// Divider ornament, as [offset from center, y] points for the right half.
// Shapes on the left are mirror images.
const SPIKE_HALF = [
  [0, 145],
  [11.6, 166],
  [4.2, 220.5],
];
const LEAF = [
  [25.8, 195.3],
  [35.5, 215.3],
  [19.7, 229],
  [11.8, 223.2],
];
const RULE_END = [
  [38.2, RULE_TOP],
  [43.4, RULE_BOTTOM],
];

const NAVY = '#0b1f3a';

function loadFont(file) {
  const bytes = readFileSync(new URL(`node_modules/${file}`, root));
  return parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
}

const round = (n) => Math.round(n * 10) / 10;

function shift(path, dx, dy) {
  for (const command of path.commands) {
    for (const [kx, ky] of [['x', 'y'], ['x1', 'y1'], ['x2', 'y2']]) {
      if (kx in command) {
        command[kx] += dx;
        command[ky] += dy;
      }
    }
  }
  return path;
}

// opentype.js's own toPathData packs numbers without separators in some cases
// (e.g. "L00"), which browsers reject, so serialize explicitly.
function pathData(path) {
  const n = (value) => String(round(value));
  return path.commands
    .map((c) => {
      switch (c.type) {
        case 'M':
        case 'L':
          return `${c.type}${n(c.x)} ${n(c.y)}`;
        case 'Q':
          return `Q${n(c.x1)} ${n(c.y1)} ${n(c.x)} ${n(c.y)}`;
        case 'C':
          return `C${n(c.x1)} ${n(c.y1)} ${n(c.x2)} ${n(c.y2)} ${n(c.x)} ${n(c.y)}`;
        case 'Z':
          return 'Z';
        default:
          throw new Error(`Unexpected path command ${c.type}`);
      }
    })
    .join('');
}

/** Sets a line of text as a single path with its cap top at y = 0 and ink starting at x = 0. */
function setText(font, text, capHeight, tracking = 0) {
  const size = (capHeight / font.charToGlyph('H').yMax) * font.unitsPerEm;
  const scale = size / font.unitsPerEm;
  const glyphs = font.stringToGlyphs(text);
  const path = new Path();
  let x = 0;

  glyphs.forEach((glyph, i) => {
    path.extend(glyph.getPath(x, capHeight, size));
    x += glyph.advanceWidth * scale + tracking;
    // Some pairs have no kerning entry and return undefined rather than 0.
    if (glyphs[i + 1]) x += (font.getKerningValue(glyph, glyphs[i + 1]) || 0) * scale;
  });

  return shift(path, -path.getBoundingBox().x1, 0);
}

/** Sets text with uniform letter spacing so its ink spans exactly `width`. */
function setTextToWidth(font, text, capHeight, width) {
  const natural = setText(font, text, capHeight).getBoundingBox().x2;
  const tracking = (width - natural) / (text.length - 1);
  return { path: setText(font, text, capHeight, tracking), natural, tracking };
}

const mirror = (points) => points.map(([x, y]) => [-x, y]).reverse();
const polygon = (points, cx) => `M${points.map(([x, y]) => `${round(cx + x)} ${round(y)}`).join('L')}Z`;

/** Divider: two rules, the center spike, and two leaves, centered on cx. */
function dividerPath(cx, ruleReach) {
  const spike = [...SPIKE_HALF, ...mirror(SPIKE_HALF).slice(0, -1)];
  const rule = [RULE_END[0], [ruleReach, RULE_TOP], [ruleReach, RULE_BOTTOM], RULE_END[1]];
  return [spike, LEAF, mirror(LEAF), rule, mirror(rule)].map((shape) => polygon(shape, cx)).join('');
}

const title = setTextToWidth(
  loadFont('@fontsource/tinos/files/tinos-latin-700-normal.woff'),
  'BEARD GROUP',
  TITLE_CAP,
  TITLE_WIDTH,
);
const tagline = setTextToWidth(
  loadFont('@fontsource/arimo/files/arimo-latin-400-normal.woff'),
  'LAW & BUSINESS PUBLISHERS',
  TAGLINE_CAP,
  TITLE_WIDTH,
);
shift(tagline.path, 0, TAGLINE_TOP);

const top = Math.floor(title.path.getBoundingBox().y1) - 1;
const fullBottom = Math.ceil(tagline.path.getBoundingBox().y2) + 1;
const compactBottom = RULE_BOTTOM + 1;
const viewBox = (bottom) => `0 ${top} ${TITLE_WIDTH} ${bottom - top}`;

const component = `---
// Generated by scripts/generate-wordmark.mjs. Edit the script, not this file.
interface Props {
  /** Include the "LAW & BUSINESS PUBLISHERS" line. */
  tagline?: boolean;
}

const { tagline = true } = Astro.props;
---

<svg
  class="wordmark"
  viewBox={tagline ? '${viewBox(fullBottom)}' : '${viewBox(compactBottom)}'}
  fill="currentColor"
  aria-hidden="true"
  focusable="false"
>
  <path d="${pathData(title.path)}" />
  <path d="${dividerPath(TITLE_WIDTH / 2, TITLE_WIDTH / 2)}" />
  {tagline && <path d="${pathData(tagline.path)}" />}
</svg>

<style>
  .wordmark {
    display: block;
    width: 100%;
    height: auto;
  }
</style>
`;

// Favicon: the divider ornament with short rules, white on a navy tile.
const favicon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <rect width="64" height="64" rx="14" fill="${NAVY}"/>
  <path fill="#fff" transform="translate(32 33) scale(0.4) translate(0 -187)" d="${dividerPath(0, 60)}"/>
</svg>
`;

writeFileSync(new URL('src/components/Wordmark.astro', root), component);
writeFileSync(new URL('public/favicon.svg', root), favicon);

console.log(`Title: natural width ${round(title.natural)}, tracking ${round(title.tracking)}`);
console.log(`Tagline: natural width ${round(tagline.natural)}, tracking ${round(tagline.tracking)}`);
console.log(`viewBox full "${viewBox(fullBottom)}", compact "${viewBox(compactBottom)}"`);
